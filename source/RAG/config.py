"""Общие настройки проекта. Всё, что может меняться, - здесь."""
from pathlib import Path

BASE_DIR = Path(__file__).parent

# Папка с материалами кейса (инструкция, матрица, методички, модули).
# По умолчанию - подпапка docs рядом с кодом, так проект работает на любом компьютере.
SOURCE_DIR = BASE_DIR / "docs"

# Куда складываем результаты обработки
DATA_DIR = BASE_DIR / "data"            # chunks.json, matrix.json, templates/*.json
VECTORS_PATH = DATA_DIR / "vectors.npy" # эмбеддинги фрагментов (numpy)

# Модели (Ollama)
EMBED_MODEL = "bge-m3"
# bge-m3 считаем на процессоре: так она не вытесняет LLM из видеопамяти (на 6 ГБ это важно),
# а один вопрос на CPU кодируется за доли секунды
EMBED_OPTIONS = {"num_gpu": 0}
LLM_MODEL = "OxW/Vikhr-Nemo-12B-Instruct-R-21-09-24:q4_K_M"
# Если LLM запущена на другом ноутбуке (с RTX 3060): "http://192.168.x.x:11434"
OLLAMA_HOST = "http://localhost:11434"

# Нарезка
MAX_CHARS = 1800        # максимальный размер фрагмента (символов)

# Поиск
TOP_K = 6               # сколько фрагментов отдаём модели
MIN_SCORE = 0.50        # порог релевантности, ниже - честный отказ.
						# Замер 23.10: нужные пункты 0.68-0.76, вопрос не по теме («пирог») 0.37
MIN_SCORE_ALONE = 0.45  # порог для самого вопроса без контекста диалога: отсекает вопросы
						# не по теме, даже если перед ними был вопрос о документах.
						# Смотрите значения в режиме python rag.py --debug и подстраивайте.
FALLBACK_SCORE = 0.65   # если модель не выбрала ни одного документа, но поиск уверен (>= порога),
						# показываем ближайший пункт дословно - без генерации, поэтому без выдумок

# Оформление документов: где ГОСТ Р 7.0.97-2025 и Инструкция по ДОУ расходятся
# (номер страницы, пробел между инициалами), какое правило применять:
#   "instruction" - внутренняя Инструкция организации (локальный акт; ГОСТ п. 3.3 сам отсылает к ним)
#   "gost"        - ГОСТ Р 7.0.97-2025
FORMAT_PRIORITY = "instruction"
