type LayoutField struct {
	Key      string
	Label    string
	Question string
	Optional bool
}

type LayoutInfo struct {
	ID string
	// Наименование вида документа (реквизит 09). У письма вида нет (п. 5.9 ГОСТ)
	Title string
	// Название в чате и в имени файла
	Name string
	Kind string
	// Корни слов, по которым запрос узнается: «служебк», «докладн»
	Keywords []string
	Fields   []LayoutField
	// Как писать текст: лицо изложения (п. 5.18 ГОСТ) и базовые фразы
	TextRule string
}

